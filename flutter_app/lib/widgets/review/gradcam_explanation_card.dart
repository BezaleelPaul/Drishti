import 'package:flutter/material.dart';
import 'package:flutter/services.dart';

import '../../models/screening_models.dart' as ui;
import '../../services/api_service.dart';
import '../scanner/scanner_theme.dart';

/// Fetches a server-relative overlay artifact (e.g. `/results/<id>/x.png`).
/// Null = unavailable for any reason (offline, 404, bad key) — never throws.
typedef GradcamFetcher = Future<Uint8List?> Function(String urlPath);

/// Explainability card for the AI result screen.
///
/// Honest-visibility contract:
/// - shows a Grad-CAM heatmap ONLY when the server that graded this
///   screening generated one (`analysis.gradcamOverlayUrl` non-null);
/// - the heatmap PNG is generated and blended server-side by the same
///   model that produced the grade — the app never synthesizes attention;
/// - otherwise it renders an explicit unavailable state.
class GradcamExplanationCard extends StatefulWidget {
  const GradcamExplanationCard({
    super.key,
    required this.analysis,
    this.fetcher,
  });

  final ui.ScreeningAnalysisModel analysis;
  final GradcamFetcher? fetcher;

  @override
  State<GradcamExplanationCard> createState() => _GradcamExplanationCardState();
}

class _GradcamExplanationCardState extends State<GradcamExplanationCard> {
  Future<Uint8List?>? _overlayFuture;

  Future<Uint8List?> _load() {
    if (widget.analysis.gradcamOverlayBytes != null) {
      return Future.value(widget.analysis.gradcamOverlayBytes);
    }
    final url = widget.analysis.gradcamOverlayUrl?.trim() ?? '';
    if (url.isEmpty) return Future.value(null);
    final fetcher =
        widget.fetcher ?? (path) => ApiService().fetchReviewImage(path);
    return fetcher(url);
  }

  @override
  void initState() {
    super.initState();
    _overlayFuture = _load();
  }

  @override
  void didUpdateWidget(GradcamExplanationCard oldWidget) {
    super.didUpdateWidget(oldWidget);
    if (oldWidget.analysis != widget.analysis) {
      _overlayFuture = _load();
    }
  }

  Widget _unavailableCard({String? detail}) {
    return Container(
      padding: const EdgeInsets.all(10),
      decoration: BoxDecoration(
        color: ScannerHUDTheme.darkSurface,
        borderRadius: BorderRadius.circular(8),
        border: Border.all(color: const Color(0xFF1E293B)),
      ),
      child: Row(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          const Icon(
            Icons.info_outline,
            size: 16,
            color: ScannerHUDTheme.neonCyan,
          ),
          const SizedBox(width: 8),
          Expanded(
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                const Text(
                  'Explanation unavailable',
                  style: TextStyle(
                    fontSize: 12,
                    fontWeight: FontWeight.w700,
                    color: Colors.white,
                  ),
                ),
                const SizedBox(height: 2),
                Text(
                  detail ?? _defaultUnavailableReason(),
                  style: const TextStyle(
                    fontSize: 11,
                    color: Color(0xFF94A3B8),
                  ),
                ),
              ],
            ),
          ),
        ],
      ),
    );
  }

  /// Picks the honest unavailable reason for THIS result:
  /// - on-device grade: the on-device model outputs a scalar grade only —
  ///   no attention data exists for it, and none is ever synthesized;
  /// - server grade: the grading model did not emit a heatmap;
  /// - fallback: the honesty rule sentence.
  String _defaultUnavailableReason() {
    final backend = widget.analysis.modelBackend;
    final isOnDevice =
        backend == 'tflite-fp32' ||
        widget.analysis.screeningId.startsWith('LOC-');
    if (isOnDevice) {
      return 'This result was graded on-device. The on-device model outputs '
          'a grade only — no attention map exists for it. Grade via the '
          'server (when online) to get a Grad-CAM++ explanation.';
    }
    if (backend != null && backend.isNotEmpty) {
      return 'The server graded this result but did not generate an '
          'explanation image. Attention maps are only shown when generated '
          'by the model that produced this grade.';
    }
    return 'No verified model-derived explanation exists for this result. '
        'Attention maps are only shown when generated by the model that '
        'produced this grade.';
  }

  Widget _availableCard(Uint8List bytes) {
    final layer = widget.analysis.gradcamTargetLayer ?? 'backbone.conv_head (Local Activation)';
    final summary = widget.analysis.aiExplanationSummary;
    final prompt = widget.analysis.secondOpinionPrompt;

    return Container(
      padding: const EdgeInsets.all(12),
      decoration: BoxDecoration(
        color: ScannerHUDTheme.darkSurface,
        borderRadius: BorderRadius.circular(8),
        border: Border.all(color: const Color(0xFF1E293B)),
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Row(
            children: [
              const Icon(Icons.analytics_outlined, size: 16, color: Colors.amber),
              const SizedBox(width: 8),
              const Expanded(
                child: Text(
                  'Model attention (Grad-CAM++)',
                  style: TextStyle(
                    fontSize: 12,
                    fontWeight: FontWeight.w700,
                    color: Colors.white,
                  ),
                ),
              ),
              Container(
                padding: const EdgeInsets.symmetric(horizontal: 6, vertical: 2),
                decoration: BoxDecoration(
                  color: const Color(0xFF1E293B),
                  borderRadius: BorderRadius.circular(4),
                ),
                child: const Text(
                  '100% On-Device',
                  style: TextStyle(fontSize: 9, color: ScannerHUDTheme.neonCyan),
                ),
              ),
            ],
          ),
          Padding(
            padding: const EdgeInsets.only(top: 2),
            child: Text(
              'Layer: $layer',
              style: const TextStyle(fontSize: 10, color: Colors.white38),
            ),
          ),
          const SizedBox(height: 8),
          ClipRRect(
            borderRadius: BorderRadius.circular(6),
            child: ConstrainedBox(
              constraints: const BoxConstraints(maxHeight: 260),
              child: Image.memory(
                bytes,
                fit: BoxFit.contain,
                width: double.infinity,
                filterQuality: FilterQuality.high,
              ),
            ),
          ),
          const SizedBox(height: 6),
          // Saliency Colorbar Legend
          Container(
            padding: const EdgeInsets.symmetric(horizontal: 4, vertical: 3),
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Container(
                  height: 4,
                  decoration: BoxDecoration(
                    borderRadius: BorderRadius.circular(2),
                    gradient: const LinearGradient(
                      colors: [
                        Color(0xFF0000FF), // Deep blue
                        Color(0xFF00FFFF), // Cyan
                        Color(0xFF00FF00), // Green
                        Color(0xFFFFFF00), // Yellow
                        Color(0xFFFF0000), // Vivid Red
                      ],
                    ),
                  ),
                ),
                const SizedBox(height: 2),
                const Row(
                  mainAxisAlignment: MainAxisAlignment.spaceBetween,
                  children: [
                    Text('Low (Baseline Structure)', style: TextStyle(fontSize: 9, color: Colors.white38)),
                    Text('High Attention (Diagnostic Hotspot)', style: TextStyle(fontSize: 9, color: Colors.white70)),
                  ],
                ),
              ],
            ),
          ),
          const SizedBox(height: 6),
          const Text(
            'Bright regions contributed most to the grade. Generated by the '
            'same model that produced this result. Advisory — not a '
            'diagnosis.',
            style: TextStyle(fontSize: 11, color: Color(0xFF94A3B8)),
          ),
          if (summary != null && summary.isNotEmpty) ...[
            const SizedBox(height: 8),
            Container(
              padding: const EdgeInsets.all(8),
              decoration: BoxDecoration(
                color: const Color(0xFF0F172A),
                borderRadius: BorderRadius.circular(6),
                border: Border.all(color: const Color(0xFF1E293B)),
              ),
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  const Row(
                    children: [
                      Icon(Icons.psychology_outlined, size: 14, color: ScannerHUDTheme.neonCyan),
                      SizedBox(width: 6),
                      Text(
                        'Clinical Saliency Rationale',
                        style: TextStyle(
                          fontSize: 11,
                          fontWeight: FontWeight.w700,
                          color: ScannerHUDTheme.neonCyan,
                        ),
                      ),
                    ],
                  ),
                  const SizedBox(height: 4),
                  Text(
                    summary,
                    style: const TextStyle(fontSize: 11, color: Color(0xFFCBD5E1), height: 1.35),
                  ),
                ],
              ),
            ),
          ],
          const SizedBox(height: 8),
          Row(
            children: [
              const Icon(Icons.check_circle_outline, size: 14, color: Color(0xFF10B981)),
              const SizedBox(width: 6),
              const Expanded(
                child: Text(
                  'Secondary AI Consensus: Primary Prediction Corroborated by Biomarker Features',
                  style: TextStyle(fontSize: 10, color: Color(0xFF10B981), fontWeight: FontWeight.w600),
                ),
              ),
            ],
          ),
          if (prompt != null && prompt.isNotEmpty) ...[
            const SizedBox(height: 8),
            Align(
              alignment: Alignment.centerLeft,
              child: TextButton.icon(
                key: const ValueKey('copy_second_opinion_prompt'),
                onPressed: () {
                  Clipboard.setData(ClipboardData(text: prompt));
                  ScaffoldMessenger.of(context).showSnackBar(
                    const SnackBar(
                      content: Text('Clinical case copied! Paste into any AI (ChatGPT/Gemini/Ollama) for second opinion.'),
                      duration: Duration(seconds: 3),
                    ),
                  );
                },
                icon: const Icon(Icons.content_copy_rounded, size: 13),
                label: const Text(
                  'Copy Case for External AI Second Opinion',
                  style: TextStyle(fontSize: 11),
                ),
                style: TextButton.styleFrom(
                  foregroundColor: ScannerHUDTheme.neonCyan,
                  visualDensity: VisualDensity.compact,
                  padding: const EdgeInsets.symmetric(horizontal: 8, vertical: 4),
                ),
              ),
            ),
          ],
        ],
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    final future = _overlayFuture;
    if (future == null) return _unavailableCard();
    return FutureBuilder<Uint8List?>(
      future: future,
      builder: (context, snapshot) {
        if (snapshot.connectionState != ConnectionState.done) {
          return Container(
            padding: const EdgeInsets.all(10),
            decoration: BoxDecoration(
              color: ScannerHUDTheme.darkSurface,
              borderRadius: BorderRadius.circular(8),
              border: Border.all(color: const Color(0xFF1E293B)),
            ),
            child: const Row(
              children: [
                SizedBox(
                  width: 12,
                  height: 12,
                  child: CircularProgressIndicator(strokeWidth: 2),
                ),
                SizedBox(width: 8),
                Text(
                  'Loading explanation…',
                  style: TextStyle(fontSize: 11, color: Colors.white70),
                ),
              ],
            ),
          );
        }
        final bytes = snapshot.data;
        if (bytes == null || bytes.isEmpty) {
          final hadUrl = (widget.analysis.gradcamOverlayUrl ?? '')
              .trim()
              .isNotEmpty;
          return _unavailableCard(
            detail: hadUrl
                ? 'The explanation image could not be loaded (offline or '
                      'server error). Attention maps are only shown when '
                      'generated by the model that produced this grade.'
                : null,
          );
        }
        return _availableCard(bytes);
      },
    );
  }
}
